export interface SmallCalcContent {
  /** Одна-две фразы под заголовком, до калькулятора. */
  lead: string
  sections: ContentSection[]
  faq: FaqItem[]
}

function must<T>(r: { ok: true; value: T } | { ok: false }): T {
  if (!r.ok) throw new Error('Пример для текста не посчитался')
  return r.value
}

function mustSum(r: SumOddsResult): { total: Decimal; totalRounded: Decimal } {
  if (!r.ok) throw new Error('Пример для текста не посчитался')
  return r
}

const dec = (s: string): Decimal => D(s)
const money = (v: Decimal): string => formatMoney(v).text

