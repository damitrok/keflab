// человек; тексты ниже — черновики. Числа в них — из движка (передаются
// аргументом), руками не набираются.

export interface IntroInput {
  k: number
  n: number
  /** Число комбинаций C(N, K). */
  combinations: number
  /** Наименьшее число зашедших событий, при котором есть выплата. */
  minWins: number
}

const key = (k: number, n: number): string => `${k}/${n}`

