// TODO(text): шаблон для остальных систем, вычитывает человек
function template(i: IntroInput): string {
  const { k, n, combinations: c, minWins } = i
  return `Система ${k} из ${n} состоит из ${eventsWord(n)}. Из них составляются все экспрессы по ${eventsWord(k)}: ${c} комбинаций. Общая ставка делится между комбинациями поровну. Чтобы появилась выплата, должны зайти минимум ${eventsWord(minWins)}. Введите ставку и коэффициенты в калькуляторе ниже, и он покажет возврат и прибыль. Калькулятор считает по формулам и не знает, чем закончатся события.`
}

/** Есть ли для системы отдельный черновик (иначе шаблон). */
export function hasHandwrittenIntro(k: number, n: number): boolean {
  return key(k, n) in POPULAR
}

export function systemIntro(input: IntroInput): string {
  return (POPULAR[key(input.k, input.n)] ?? template)(input)
}
